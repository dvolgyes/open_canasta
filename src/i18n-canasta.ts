const localeIndexes = {
	de: 1,
	hu: 2,
	no: 3,
	es: 4,
	pt: 5,
	fr: 6,
	it: 7,
	nl: 8,
} as const;
type CanastaLocale = keyof typeof localeIndexes;
type Catalog = Readonly<Record<string, string>>;

/** Adds the canasta table's texts to each language's catalog. */
export function withCanastaTexts(
	catalogs: Readonly<Record<CanastaLocale, Catalog>>,
): Readonly<Record<CanastaLocale, Catalog>> {
	return Object.fromEntries(
		Object.entries(localeIndexes).map(([locale, index]) => [
			locale,
			{
				...catalogs[locale as CanastaLocale],
				...Object.fromEntries(rows.map((row) => [row[0], row[index]])),
			},
		]),
	) as Readonly<Record<CanastaLocale, Catalog>>;
}
